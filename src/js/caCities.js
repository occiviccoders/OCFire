export function nearestCity(lat, lng) {
    const cos = Math.cos(lat * Math.PI / 180);
    let best = null;
    let bestD = Infinity;
    for (const [name, clat, clng] of CA_CITIES) {
        const dlat = lat - clat;
        const dlng = (lng - clng) * cos;
        const d = dlat * dlat + dlng * dlng;
        if (d < bestD) { bestD = d; best = name; }
    }
    return best;
}
